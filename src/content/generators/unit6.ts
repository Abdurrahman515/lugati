/* ───────── الأسماء الموصولة ───────── */
const OD: Record<string, string> = {
  'الذي': 'للمفرد المذكر', 'التي': 'للمفردة المؤنثة', 'اللذان': 'للمثنى المذكر في حالة الرفع', 'اللتان': 'للمثنى المؤنث في حالة الرفع',
  'الذين': 'لجمع المذكر', 'اللاتي': 'لجمع المؤنث', 'مَن': 'للعاقل', 'ما': 'لغير العاقل',
}
const OB: [string, string][] = [
  ['الطالبُ ___ اجتهدَ ناجحٌ', 'الذي'], ['الطالبةُ ___ اجتهدتْ ناجحةٌ', 'التي'], ['الطالبانِ ___ اجتهدا ناجحانِ', 'اللذان'],
  ['الطالبتانِ ___ اجتهدتا ناجحتانِ', 'اللتان'], ['الطلابُ ___ اجتهدوا ناجحونَ', 'الذين'], ['الطالباتُ ___ اجتهدنَ ناجحاتٌ', 'اللاتي'],
  ['أحترمُ ___ يحترمُ الآخرينَ', 'مَن'], ['أحبُّ ___ ينفعُ الناسَ من الأعمالِ', 'ما'],
]
const OS: [string, string, string, string, string][] = [ // [الجملة، الصلة، خطأ ١، خطأ ٢]
  ['جاءَ الطالبُ الذي حفظَ القصيدةَ', 'حفظَ القصيدةَ', 'جاءَ الطالبُ', 'الطالبُ الذي', ''],
  ['كرّمَ المديرُ الطالباتِ اللاتي تفوّقنَ', 'تفوّقنَ', 'كرّمَ المديرُ', 'الطالباتِ اللاتي', ''],
  ['قابلتُ الرجلَ الذي يصنعُ الفخّارَ', 'يصنعُ الفخّارَ', 'قابلتُ الرجلَ', 'الرجلَ الذي', ''],
]
export function genMawsul(): MC {
  if (Math.random() < 0.75) {
    const [s, right] = pick(OB)
    const d = OD[right]
    const wrongs: Pair[] = Object.keys(OD).filter((k) => k !== right).map((k) => [k, `«${k}» ${OD[k]}، وهاد مو المطلوب هون. أما المطلوب فاسم موصول ${d}.`])
    return build(`أكملي بالاسم الموصول المناسب: ${s}`, [right, `هون بنحتاج اسم موصول ${d}، وهو «${right}».`], wrongs)
  }
  const [s, right, a, b] = pick(OS)
  const g = 'جملة الصلة هي اللي بتجي بعد الاسم الموصول وبتكمّل معناه'
  return build(`ما جملة الصلة في: «${s}»؟`, [right, `جملة الصلة «${right}»؛ بتجي بعد الاسم الموصول وبتتمّم معناه.`], [[a, `«${a}» مو جملة الصلة. ${g}.`], [b, `«${b}» فيه الاسم الموصول نفسه وما بيكفي. ${g}.`]], 2)
}

/* ───────── إعراب الفعل المضارع ───────── */
const MDS: Record<string, string> = {
  'مرفوع': 'إذا ما سبقه ناصب ولا جازم',
  'منصوب': 'إذا سبقه ناصب مثل أن ولن وكي',
  'مجزوم': 'إذا سبقه جازم مثل لم ولا الناهية ولام الأمر',
}
const MS: [string, string, string, string][] = [
  ['الطالبُ يكتبُ الدرسَ', 'يكتبُ', 'مرفوع', 'ما سبقه ناصب ولا جازم'],
  ['سيسافرُ أبي غداً', 'يسافرُ', 'مرفوع', 'سبقه السين، وهي ما بتنصب ولا بتجزم'],
  ['لن يكتبَ الطالبُ الدرسَ', 'يكتبَ', 'منصوب', 'سبقه (لن)'],
  ['أريدُ أن أقرأَ كتاباً', 'أقرأَ', 'منصوب', 'سبقه (أن)'],
  ['ادرسْ كي تنجحَ', 'تنجحَ', 'منصوب', 'سبقه (كي)'],
  ['لم يكتبْ الطالبُ الدرسَ', 'يكتبْ', 'مجزوم', 'سبقه (لم)'],
  ['لا تُهملْ دروسَكَ', 'تُهملْ', 'مجزوم', 'سبقه (لا) الناهية'],
  ['لِيَجتهدْ كلُّ طالبٍ', 'يجتهدْ', 'مجزوم', 'سبقه لام الأمر'],
]
const NOUN: [string, string, string, string][] = [ // [الجملة، الفعل، العلامة، السبب]
  ['الطلابُ يكتبونَ الدرسَ', 'يكتبونَ', 'ثبوت النون', 'مرفوع من الأفعال الخمسة'],
  ['الطالبتانِ تكتبانِ الدرسَ', 'تكتبانِ', 'ثبوت النون', 'مرفوع من الأفعال الخمسة'],
  ['لن يكتبوا الدرسَ', 'يكتبوا', 'حذف النون', 'منصوب من الأفعال الخمسة'],
  ['لم يكتبوا الدرسَ', 'يكتبوا', 'حذف النون', 'مجزوم من الأفعال الخمسة'],
]
const ND: Record<string, string> = {
  'ثبوت النون': 'علامة رفع الأفعال الخمسة', 'حذف النون': 'علامة نصب وجزم الأفعال الخمسة',
  'الضمة': 'علامة رفع الفعل صحيح الآخر', 'الفتحة': 'علامة نصب الفعل صحيح الآخر',
}
export function genMudari(): MC {
  const r = Math.random()
  if (r < 0.5) {
    const [s, v, t, why] = pick(MS)
    const wrongs: Pair[] = Object.keys(MDS).filter((k) => k !== t).map((k) => [k, `«${k}»: ${MDS[k]}. أما هون فالفعل ${why}.`])
    return build(`ما حالة الفعل المضارع «${v}» في: ${s}؟`, [t, `«${v}» ${t}، لأنو ${why}.`], wrongs, 2)
  }
  if (r < 0.65) {
    const right = pick(['لم', 'لا الناهية', 'لام الأمر'])
    return build('أي الأدوات الآتية تجزم الفعل المضارع؟', [right, `«${right}» من أدوات الجزم: لم، لا الناهية، لام الأمر.`], ['لن', 'أن', 'كي'].map((t): Pair => [t, `«${t}» حرف نصب، بينصب الفعل وما بيجزمه.`]))
  }
  if (r < 0.8) {
    const right = pick(['لن', 'أن', 'كي'])
    return build('أي الأدوات الآتية تنصب الفعل المضارع؟', [right, `«${right}» من أدوات النصب: أن، لن، كي.`], ['لم', 'لا الناهية', 'لام الأمر'].map((t): Pair => [t, `«${t}» حرف جزم، بيجزم الفعل وما بينصبه.`]))
  }
  const [s, v, sign, why] = pick(NOUN)
  const wrongs: Pair[] = Object.keys(ND).filter((k) => k !== sign).map((k) => [k, `«${k}» ${ND[k]}. أما هون فالفعل ${why}.`])
  return build(`ما علامة إعراب الفعل المضارع «${v}» في: ${s}؟`, [sign, `«${v}» ${why}، وعلامته ${sign}.`], wrongs, 3)
}

/* ───────── علامات الاختصار ───────── */
const AM: Record<string, string> = { 'سؤال': 'س', 'جواب': 'ج', 'ميلادية': 'م', 'هجرية': 'هـ', 'طبعة': 'ط', 'إلى آخره': 'إلخ' }
const AB: [string, string, string][] = [
  ['س', 'سؤال', 'س: ما عاصمة المملكة؟'], ['ج', 'جواب', 'ج: عاصمتها الرياض.'],
  ['م', 'ميلادية', 'وُلد الشاعر سنة ١٩٦١م'], ['هـ', 'هجرية', 'وُلد الشاعر سنة ١٣٨١هـ'],
  ['ط', 'طبعة', 'دليل الإملاء، ط ٢'], ['إلخ', 'إلى آخره', 'في الحديقة ورودٌ وأشجارٌ وطيورٌ، إلخ'],
]
export function genIkhtisar(): MC {
  const [a, m, ex] = pick(AB)
  const wrongs: Pair[] = Object.keys(AM).filter((k) => k !== m).map((k) => [k, `«${k}» اختصارها «${AM[k]}»، مو «${a}».`])
  return build(`ماذا تعني علامة الاختصار «${a}» في: ${ex}؟`, [m, `الاختصار «${a}» معناه ${m}.`], wrongs, 3)
}
