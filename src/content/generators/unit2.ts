const NN: [string[], number, number][] = [
  [['كانَ', 'الطالبُ', 'مجتهدًا'], 1, 2], [['أصبحَ', 'الجوُّ', 'لطيفًا'], 1, 2], [['صارَ', 'الولدُ', 'رجلًا'], 1, 2],
  [['ليسَ', 'الصدقُ', 'ضعفًا'], 1, 2], [['ظلَّ', 'المسلمُ', 'صابرًا'], 1, 2], [['أمسى', 'الطقسُ', 'باردًا'], 1, 2],
]
export function genNasikh(): MC {
  const r = Math.random()
  if (r < 0.34) {
    const [v, s] = pick(NS)
    const wrongs: Pair[] = Object.keys(NM).filter((k) => k !== v).map((k) => [
      NM[k], `هاد معنى «${k}». أما «${v}» فبتفيد: ${NM[v]}.`,
    ])
    return build(`ما المعنى الذي يضيفه الفعل الناسخ «${v}» في: ${s}؟`, [NM[v], `«${v}» بتفيد ${NM[v]}.`], wrongs)
  }
  if (r < 0.68) {
    const [s, w, kind, sign] = pick(NK)
    const wrongs: Pair[] = Object.keys(NSIGN).filter((k) => k !== sign).map((k) => [
      k, `«${k}»: ${NSIGN[k]}. أما «${w}» فهو ${kind} وعلامة نصبه ${sign}.`,
    ])
    return build(`ما علامة نصب خبر الفعل الناسخ «${w}» في: ${s}؟`, [sign, `«${w}» ${kind}، و«${sign}» ${NSIGN[sign]}.`], wrongs)
  }
  const [ws, ni, ki] = pick(NN)
  return build(`في الجملة «${ws.join(' ')}» أي كلمة تُعرب اسماً للفعل الناسخ؟`, [ws[ni], `«${ws[ni]}» هو الاسم المرفوع اللي دخل عليه الناسخ، وبيسمى اسم ${strip0(ws[0])}.`], [
    [ws[ki], `«${ws[ki]}» هو خبر الفعل الناسخ، وهو منصوب، مو اسمه.`],
    [ws[0], `«${ws[0]}» هو الفعل الناسخ نفسه، مو اسمه.`],
  ], 2)
}
const strip0 = (s: string) => s.replace(/[\u064B-\u065F]/g, '')

