/* ───────── المفرد من حيث آخره ───────── */
const ED: Record<string, string> = {
  'صحيح': 'ما لا ينتهي بألف لازمة ولا ياء لازمة مكسور ما قبلها ولا همزة قبلها ألف زائدة',
  'مقصور': 'ما آخره ألف لازمة مفتوح ما قبلها',
  'منقوص': 'ما آخره ياء لازمة مكسور ما قبلها',
  'ممدود': 'ما آخره همزة قبلها ألف زائدة',
}
const EB: [string, string][] = [
  ['مسجد', 'صحيح'], ['رحمة', 'صحيح'], ['درهم', 'صحيح'], ['رسول', 'صحيح'], ['كتاب', 'صحيح'], ['مدرسة', 'صحيح'],
  ['الدنيا', 'مقصور'], ['أذى', 'مقصور'], ['ثرى', 'مقصور'], ['أسخى', 'مقصور'], ['عصا', 'مقصور'], ['فتى', 'مقصور'], ['هدى', 'مقصور'],
  ['القاضي', 'منقوص'], ['الداعي', 'منقوص'], ['النادي', 'منقوص'], ['العالي', 'منقوص'], ['الهادي', 'منقوص'], ['الساعي', 'منقوص'],
  ['مساء', 'ممدود'], ['دعاء', 'ممدود'], ['القضاء', 'ممدود'], ['كساء', 'ممدود'], ['صحراء', 'ممدود'], ['ابتداء', 'ممدود'],
]
export function genMufrad(): MC {
  const [w, t] = pick(EB)
  const wrongs: Pair[] = Object.keys(ED).filter((k) => k !== t).map((k) => [
    k, `«${k}»: ${ED[k]}. أما «${w}» فهو ${t} لأنو ${ED[t]}.`,
  ])
  return build(`ما نوع الاسم المفرد «${w}» من حيث آخره؟`, [t, `«${w}» ${t}، يعني ${ED[t]}.`], wrongs)
}

/* ───────── المثنى ───────── */
const MT: [string, string, string, string][] = [
  ['طالب', 'طالبان', 'طالبين', 'طلاب'], ['معلم', 'معلمان', 'معلمين', 'معلمون'], ['مدرسة', 'مدرستان', 'مدرستين', 'مدارس'],
  ['طالبة', 'طالبتان', 'طالبتين', 'طالبات'], ['كتاب', 'كتابان', 'كتابين', 'كتب'], ['قلم', 'قلمان', 'قلمين', 'أقلام'],
  ['مسلم', 'مسلمان', 'مسلمين', 'مسلمون'], ['عالم', 'عالمان', 'عالمين', 'علماء'], ['مرصد', 'مرصدان', 'مرصدين', 'مراصد'],
  ['مدينة', 'مدينتان', 'مدينتين', 'مدن'],
]
export function genMuthanna(): MC {
  const [m, d, dj, pl] = pick(MT)
  const rafa = Math.random() < 0.5
  const right = rafa ? d : dj
  const wrongs: Pair[] = [
    [rafa ? dj : d, rafa
      ? `«${dj}» مثنى بس بالياء والنون، وهاي علامة النصب والجر؛ والسؤال عن حالة الرفع.`
      : `«${d}» مثنى بس بالألف والنون، وهاي علامة الرفع؛ والسؤال عن النصب والجر.`],
    [pl, `«${pl}» جمع بيدل على أكتر من اثنين، مو مثنى.`],
    [m, `«${m}» مفرد بيدل على واحد، وما انزادت عليه علامة التثنية.`],
  ]
  return build(`ما مثنى «${m}» في حالة ${rafa ? 'الرفع' : 'النصب والجر'}؟`, [right,
    `المثنى بنزيد فيه ${rafa ? 'ألف ونون' : 'ياء ونون'} على المفرد بحالة ${rafa ? 'الرفع' : 'النصب والجر'}.`], wrongs)
}

