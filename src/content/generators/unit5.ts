/* ───────── أسماء الإشارة ───────── */
const SD: Record<string, string> = {
  'هذا': 'للمفرد المذكر القريب', 'هذه': 'للمفردة المؤنثة القريبة', 'هذان': 'للمثنى المذكر القريب', 'هاتان': 'للمثنى المؤنث القريب',
  'هؤلاء': 'للجمع القريب', 'ذلك': 'للمفرد المذكر البعيد', 'تلك': 'للمفردة المؤنثة البعيدة', 'أولئك': 'للجمع البعيد',
}
const SB: [string, string, string][] = [
  ['___ كتابٌ مفيدٌ', 'هذا', 'مفرد مذكر قريب'], ['___ حقيبةٌ جميلةٌ', 'هذه', 'مفردة مؤنثة قريبة'],
  ['___ الطالبانِ مجتهدانِ', 'هذان', 'مثنى مذكر قريب'], ['___ الطالبتانِ مجتهدتانِ', 'هاتان', 'مثنى مؤنث قريب'],
  ['___ الطلابُ مخلصونَ', 'هؤلاء', 'جمع قريب'], ['___ الجبلُ عالٍ', 'ذلك', 'مفرد مذكر بعيد'],
  ['___ المدينةُ كبيرةٌ', 'تلك', 'مفردة مؤنثة بعيدة'], ['___ الطلابُ نشيطونَ', 'أولئك', 'جمع بعيد'],
]
const PL: [string, string][] = [['قريب منكِ في المكان', 'هنا'], ['متوسط البعد عنكِ في المكان', 'هناك'], ['بعيد عنكِ في المكان', 'هنالك']]
export function genIshara(): MC {
  const r = Math.random()
  if (r < 0.6) {
    const [s, right, d] = pick(SB)
    const wrongs: Pair[] = Object.keys(SD).filter((k) => k !== right).map((k) => [k, `«${k}» ${SD[k]}، وهاد مو المقصود هون. أما المطلوب فهو ${d}.`])
    return build(`أكملي بالاسم الإشارة المناسب: ${s} (${d})`, [right, `هون المطلوب اسم إشارة ${d}، وهو «${right}».`], wrongs)
  }
  if (r < 0.8) {
    const [d, right] = pick(PL)
    const wrongs: Pair[] = PL.filter((p) => p[1] !== right).map(([, t]): Pair => [t, `«${t}» لمكان غير هيك. أما هون فالمكان ${d}.`])
    wrongs.push(['هذا', '«هذا» اسم إشارة للمفرد المذكر مو للمكان.'])
    return build(`ما اسم الإشارة للمكان ${d}؟`, [right, `«${right}» اسم إشارة للمكان ${d}.`], wrongs)
  }
  const right = pick(['هذان', 'هاتان'])
  const wrongs: Pair[] = ['هذا', 'هذه', 'هؤلاء', 'ذلك'].map((t): Pair => [t, `«${t}» اسم إشارة مبني، وآخره ما بيتغير.`])
  return build('أي أسماء الإشارة الآتية معرب؟', [right, 'أسماء الإشارة كلها مبنية، إلا المثنى منها فهو معرب.'], wrongs)
}

