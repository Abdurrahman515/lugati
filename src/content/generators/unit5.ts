  const s = pick(TC)
  const t = 'الفاصلة (،)'
  const wrongs: Pair[] = ['النقطة (.)', 'علامة الاستفهام (؟)'].map((k): Pair => [k, `«${k}» ${TD[k]}. أما هون فالأجزاء متشابهة وبينها فصل خفيف.`])
