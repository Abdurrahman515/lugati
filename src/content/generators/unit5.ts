export function genIdafa(): MC {
  if (Math.random() < 0.5) {
    const [s, m, i, o] = pick(IA)
    return build(`ما المضاف إليه في: «${s}»؟`, [i, `«${i}» اسم جاء بعد «${m}» وكمّل معناه، فهو المضاف إليه ومجرور دائماً.`], [
      [m, `«${m}» هو المضاف: بيتعرب حسب موقعه بالجملة. أما المضاف إليه فهو الاسم اللي بعده.`],
      [o, `«${o}» ما إلو علاقة بالإضافة هون.`],
    ], 2)
  }
  return signQuestion(pick(IS), 'المضاف إليه')
}

