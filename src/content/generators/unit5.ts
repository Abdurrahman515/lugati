/* ───────── الهمزة المتوسطة (ألف/واو/ياء) — مشتركة بين الوحدتين ٥ و٦ ───────── */
const RANK: Record<string, number> = { 'السكون': 0, 'الفتحة': 1, 'الضمة': 2, 'الكسرة': 3 }
const LET = ['', 'ألف', 'واو', 'ياء']
const MAP: Record<string, string> = { 'ألف': 'الفتحة', 'واو': 'الضمة', 'ياء': 'الكسرة' }
/** [الكلمة، حركة الهمزة، حركة ما قبلها] */
export const HW: [string, string, string][] = [
  ['تَأْخِير', 'السكون', 'الفتحة'], ['رَأْس', 'السكون', 'الفتحة'], ['فَأْس', 'السكون', 'الفتحة'], ['يَأْكُلُ', 'السكون', 'الفتحة'],
  ['مَسْأَلَة', 'الفتحة', 'السكون'], ['نَشْأَة', 'الفتحة', 'السكون'], ['جُزْأَيْن', 'الفتحة', 'السكون'],
  ['تَأَمُّل', 'الفتحة', 'الفتحة'], ['سَأَلَ', 'الفتحة', 'الفتحة'],
  ['شُؤُون', 'الضمة', 'الضمة'], ['رُؤُوس', 'الضمة', 'الضمة'], ['سُؤَال', 'الفتحة', 'الضمة'], ['مُؤْمِن', 'السكون', 'الضمة'],
  ['تَفَاؤُل', 'الضمة', 'السكون'], ['يَمْلَؤُهَا', 'الضمة', 'الفتحة'], ['رُؤْيَة', 'السكون', 'الضمة'],
  ['فِئَة', 'الفتحة', 'الكسرة'], ['بِئْر', 'السكون', 'الكسرة'], ['سُئِلَ', 'الكسرة', 'الضمة'], ['مِئَة', 'الفتحة', 'الكسرة'], ['ذِئْب', 'السكون', 'الكسرة'],
]
/** الحرف الذي ترسم عليه الهمزة: يناسب أقوى الحركتين (الكسرة ثم الضمة ثم الفتحة). */
export function hamzaLetter(h: string, p: string): string { return LET[Math.max(RANK[h], RANK[p])] }
export function genHamza(): MC {
  const [w, h, p] = pick(HW)
  const l = hamzaLetter(h, p)
  const strong = MAP[l]
  const reason = p === 'السكون' ? `الهمزة ${h.replace('ال', '')} وما قبلها ساكن، فنكتبها على ما يناسب حركتها` : h === 'السكون' ? `الهمزة ساكنة، فنكتبها على ما يناسب حركة الحرف اللي قبلها` : `حركة الهمزة ${h.replace('ال', '')} وحركة ما قبلها ${p.replace('ال', '')}، وأقواهما ${strong.replace('ال', '')}`
  const wrongs: Pair[] = ['ألف', 'واو', 'ياء'].filter((x) => x !== l).map((x): Pair => [x, `بتنكتب الهمزة على «${x}» لما تكون أقوى الحركتين ${MAP[x]}. أما هون فـ${reason}.`])
  return build(`على أي حرف تُكتب الهمزة المتوسطة في كلمة «${w}»؟`, [l, `${reason}، يعني على ${l}.`], wrongs, 2)
}

