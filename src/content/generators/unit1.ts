export function genAmr(): MC {
  const [p, m, c, f] = pick(AM)
  if (Math.random() < 0.65) {
    const wrongs: Pair[] = [
      [m, `«${m}» فعل ماضٍ بيدل على شي صار، وما فيه طلب.`],
      ['أ' + p.slice(1), `«${'أ' + p.slice(1)}» فعل مضارع للمتكلم، مو طلب من مخاطب.`],
      [f, `«${f}» اسم فاعل، مو فعل.`],
      [p, `«${p}» هو الفعل المضارع نفسه اللي بالسؤال، وإحنا بدنا صيغة الطلب.`],
    ]
    return build(`ما فعل الأمر من الفعل المضارع «${p}»؟`, [c, `فعل الأمر بيطلب وقوع الفعل من المخاطب، وهو من «${p}»: «${c}».`], wrongs)
  }
  const right: Pair = ['همزة وصل', `«${m}» فعل ثلاثي، وأمر الفعل الثلاثي بيبدأ بهمزة وصل (${strip(c)}).`]
  return build(`ما نوع الهمزة في أول فعل الأمر «${c}»؟`, right, [
    ['همزة قطع', `همزة القطع بتكون بأمر الفعل الرباعي مثل «أكرِمْ». أما «${m}» ثلاثي فأمره بيبدأ بهمزة وصل.`],
    ['ألف مد', 'الألف المدية ما بتقع بأول الكلمة؛ هاي همزة بتنكتب ألف.'],
  ], 2)
}

