function genHamza(wasl: boolean): MC {
  const main = HAMZA.filter((h) => h[1] === (wasl ? 'وصل' : 'قطع'))
  const rest = HAMZA.filter((h) => h[1] !== (wasl ? 'وصل' : 'قطع'))
  const it = Math.random() < 0.7 ? pick(main) : pick(rest)
  const [w, t, r] = it
  const right: Pair = [t === 'وصل' ? 'همزة وصل' : 'همزة قطع', `«${w}» ${r}، يعني همزتها ${t}.`]
  return build(`ما نوع الهمزة في أول «${w}»؟`, right, [
    [t === 'وصل' ? 'همزة قطع' : 'همزة وصل', t === 'وصل'
      ? `همزة القطع بينطق فيها بأول الكلام ووسطه، أما «${w}» (${r}) فهمزتها وصل وبتسقط لما نوصلها بما قبلها.`
      : `همزة الوصل بينطق فيها بالابتداء بس وبتسقط عند الوصل، أما «${w}» (${r}) فهمزتها قطع وبينطق فيها دايماً.`],
    ['ألف مد', 'الألف المدية ناتجة عن إشباع الفتحة وما بتقع بأول الكلمة؛ فهاي همزة.'],
  ], 2)
}
