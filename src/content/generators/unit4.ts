const MU = ['كتاب', 'معلمة', 'مدينة', 'طالبان', 'حديقة', 'قلم', 'معلمون', 'سماء', 'شجرة', 'بيوت']
export function genMabni(): MC {
  if (Math.random() < 0.6) {
    const [w, t] = pick(MK)
    const wrongs: Pair[] = Object.keys(MD).filter((k) => k !== t).map((k) => [k, `«${k}»: ${MD[k]}. أما «${w}» فهو ${t}.`])
    return build(`ما نوع الاسم المبني «${w}»؟`, [t, `«${w}» ${t}، وهاد من الأسماء المبنية.`], wrongs, 4)
  }
  const mabni = Math.random() < 0.5
  const w = mabni ? pick(MK)[0] : pick(MU)
  const right = mabni ? 'مبني' : 'معرب'
  const wrong: Pair = mabni
    ? ['معرب', '«معرب»: بيتغير شكل آخره بتغيّر موقعه بالجملة. أما «' + w + '» فهو مبني وبيلزم حركة وحدة.']
    : ['مبني', '«مبني»: ما بيتغير شكل آخره مهما تغيّر موقعه. أما «' + w + '» فهو معرب وبتتبدل علامته.']
  return build(`هل الاسم «${w}» معرب أم مبني؟`, [right, mabni ? `«${w}» من الأسماء المبنية، ما بيتغير آخره.` : `«${w}» اسم معرب، آخره بيتغير حسب موقعه.`], [wrong], 1)
}

