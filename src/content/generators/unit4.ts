/** علامات جر الاسم (مشتركة بين الجر بالحرف والجر بالإضافة). */
export const SGN: Record<string, string> = {
  'الكسرة': 'علامة جر المفرد وجمع التكسير وجمع المؤنث السالم',
  'الياء': 'علامة جر المثنى وجمع المذكر السالم والأسماء الخمسة',
  'الضمة': 'علامة رفع أصلية، مو علامة جر',
  'الفتحة': 'علامة نصب أصلية، مو علامة جر',
}
export type SignItem = [string, string, string, string] // [الجملة، الكلمة، نوعها، العلامة]
export function signQuestion(it: SignItem, what: string): MC {
  const [s, w, kind, sign] = it
  const wrongs: Pair[] = Object.keys(SGN).filter((k) => k !== sign).map((k) => [k, `«${k}»: ${SGN[k]}. أما «${w}» فهو ${kind} وعلامة جره ${sign}.`])
  return build(`ما علامة جر ${what} «${w}» في: ${s}؟`, [sign, `«${w}» ${kind}، وعلامة جره ${sign}.`], wrongs)
}

