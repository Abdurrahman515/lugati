/* ───────── الجمع ───────── */
const JD: Record<string, { l: string; d: string }> = {
  ms: { l: 'جمع مذكر سالم', d: 'ما دل على أكثر من اثنين بزيادة واو ونون (أو ياء ونون) على آخر مفرده مع سلامة صورته' },
  fs: { l: 'جمع مؤنث سالم', d: 'ما دل على أكثر من اثنتين بزيادة ألف وتاء على آخر مفرده مع سلامة صورته' },
  tk: { l: 'جمع تكسير', d: 'ما دل على أكثر من اثنين وتغيرت صورة مفرده عند الجمع' },
}
const JB: [string, string, string][] = [
  ['معلمون', 'ms', 'معلم'], ['مهندسون', 'ms', 'مهندس'], ['مسلمين', 'ms', 'مسلم'], ['جيولوجيون', 'ms', 'جيولوجي'],
  ['مخلصون', 'ms', 'مخلص'], ['عاملين', 'ms', 'عامل'],
  ['طالبات', 'fs', 'طالبة'], ['مواطنات', 'fs', 'مواطنة'], ['معلمات', 'fs', 'معلمة'], ['ثروات', 'fs', 'ثروة'],
  ['اتفاقات', 'fs', 'اتفاق'], ['طاقات', 'fs', 'طاقة'], ['مجالات', 'fs', 'مجال'],
  ['كتب', 'tk', 'كتاب'], ['رجال', 'tk', 'رجل'], ['أقلام', 'tk', 'قلم'], ['قلوب', 'tk', 'قلب'], ['علماء', 'tk', 'عالم'],
  ['بيوت', 'tk', 'بيت'], ['رسل', 'tk', 'رسول'], ['آمال', 'tk', 'أمل'], ['بلاد', 'tk', 'بلد'], ['صخور', 'tk', 'صخرة'],
]
export function genJam(): MC {
  const [w, c, s] = pick(JB)
  const reason = c === 'tk' ? `تغيّرت صورة مفرده (${s}) لما انجمع` : c === 'ms' ? `مفرده (${s}) سلم وزدنا عليه علامة جمع المذكر` : `مفرده (${s}) سلم وزدنا عليه ألف وتاء`
  const wrongs: Pair[] = Object.keys(JD).filter((k) => k !== c).map((k) => [
    JD[k].l, `«${JD[k].l}»: ${JD[k].d}. أما «${w}» فهو ${JD[c].l}؛ ${reason}.`,
  ])
  return build(`ما نوع الجمع في كلمة «${w}»؟`, [JD[c].l, `«${w}» ${JD[c].l}؛ ${reason}.`], wrongs)
}
export function genTakseer(): MC {
  const tk = JB.filter((j) => j[1] === 'tk')
  const [w, , s] = pick(tk)
  const wrongs: Pair[] = tk.filter((j) => j[2] !== s).map((j) => [j[2], `«${j[2]}» مفرد «${j[0]}»، مو مفرد «${w}».`])
  return build(`ما مفرد جمع التكسير «${w}»؟`, [s, `مفرد «${w}» هو «${s}»، وتغيّرت صورته لما انجمع.`], wrongs)
}

/* ───────── الحروف الناسخة ───────── */
const HM: Record<string, string> = {
  'إنَّ': 'التوكيد', 'كأنَّ': 'التشبيه', 'ليتَ': 'التمني', 'لعلَّ': 'الترجي', 'لكنَّ': 'الاستدراك',
}
const HB: [string, string, string][] = [
  ['ـــ العلمَ نورٌ', 'إنَّ', 'التوكيد'], ['ـــ الصدقَ منجاةٌ', 'إنَّ', 'التوكيد'],
  ['ـــ وجهَهُ بدرٌ', 'كأنَّ', 'التشبيه'], ['ـــ الجبيلَ قلعةٌ صناعيةٌ', 'كأنَّ', 'التشبيه'],
  ['ـــ الشبابَ يعودُ يومًا', 'ليتَ', 'التمني'], ['ـــ الأيامَ تعودُ كما كانت', 'ليتَ', 'التمني'],
  ['ـــ الغيثَ قريبٌ', 'لعلَّ', 'الترجي'], ['ـــ اللهَ يشفي مريضَنا', 'لعلَّ', 'الترجي'],
  ['الطالبُ مجتهدٌ ـــ أخاهُ كسولٌ', 'لكنَّ', 'الاستدراك'], ['المدينةُ جميلةٌ ـــ طقسَها حارٌّ', 'لكنَّ', 'الاستدراك'],
]
const HS: Record<string, string> = {
  'الفتحة': 'علامة النصب الأصلية للمفرد وجمع التكسير', 'الكسرة': 'علامة نصب جمع المؤنث السالم',
  'الياء': 'علامة نصب المثنى وجمع المذكر السالم', 'الألف': 'علامة نصب الأسماء الخمسة',
}
const HN: [string, string, string, string][] = [
  ['إنَّ المعلمَ مخلصٌ', 'المعلمَ', 'مفرد', 'الفتحة'], ['إنَّ المعلمين مخلصون', 'المعلمين', 'جمع مذكر سالم', 'الياء'],
  ['إنَّ المعلماتِ مخلصاتٌ', 'المعلماتِ', 'جمع مؤنث سالم', 'الكسرة'], ['إنَّ الطالبَينِ مجتهدان', 'الطالبَينِ', 'مثنى', 'الياء'],
  ['لعلَّ الكتبَ مفيدةٌ', 'الكتبَ', 'جمع تكسير', 'الفتحة'], ['كأنَّ أباكَ حاضرٌ', 'أباكَ', 'من الأسماء الخمسة', 'الألف'],
  ['ليتَ أخاكَ حاضرٌ', 'أخاكَ', 'من الأسماء الخمسة', 'الألف'], ['إنَّ المهندسين ماهرون', 'المهندسين', 'جمع مذكر سالم', 'الياء'],
]
export function genHarf(): MC {
  if (Math.random() < 0.5) {
    const [s, h, m] = pick(HB)
    const wrongs: Pair[] = Object.keys(HM).filter((k) => k !== h).map((k) => [
      k, `«${k}» بتفيد ${HM[k]}، وما بتناسب المعنى المطلوب هون وهو ${m}.`,
    ])
    return build(`اختر الحرف الناسخ المناسب لمعنى (${m}): ${s}`, [h, `«${h}» بتفيد ${m}.`], wrongs)
  }
  const [s, w, kind, sign] = pick(HN)
  const wrongs: Pair[] = Object.keys(HS).filter((k) => k !== sign).map((k) => [
    k, `«${k}»: ${HS[k]}. أما «${w}» فهو ${kind} وعلامة نصبه ${sign}.`,
  ])
  return build(`ما علامة نصب اسم الحرف الناسخ «${w}» في: ${s}؟`, [sign, `«${w}» ${kind}، و«${sign}» ${HS[sign]}.`], wrongs)
}

/* ───────── النداء ───────── */
const NOT: [string, string][] = [
  ['هل', 'أداة استفهام'], ['لم', 'حرف جزم ونفي'], ['قد', 'حرف تحقيق'], ['لا', 'حرف نفي'], ['ما', 'أداة استفهام أو نفي'],
]
const NM_: [string, boolean][] = [
  ['الطالبُ', true], ['المعلمُ', true], ['الجنديُّ', true], ['المواطنُ', true], ['الرجلُ', true],
  ['الطالبةُ', false], ['المعلمةُ', false], ['المواطنةُ', false], ['الفتاةُ', false], ['الأختُ', false],
]
export function genNida(): MC {
  if (Math.random() < 0.4) {
    const right = pick(['يا', 'أيا', 'هيا'])
    const wrongs: Pair[] = NOT.map(([t, d]) => [t, `«${t}» ${d}، وما هي من حروف النداء.`] as Pair)
    return build('أي هذه الكلمات حرف نداء؟', [right, `حروف النداء هي يا وأيا وهيا.`], wrongs)
  }
  const [n, male] = pick(NM_)
  const right = male ? 'أيها' : 'أيتها'
  const wrong = male ? 'أيتها' : 'أيها'
  return build(`أكمل بما يناسب نداء ما فيه (ال): يا ـــ ${n}، اجتهدْ`, [right,
    `إذا بدنا ننادي اسم فيه (ال) منجيب بـ(${right}) ${male ? 'للمذكر' : 'للمؤنث'}، و«${n}» ${male ? 'مذكر' : 'مؤنث'}.`], [
    [wrong, `«${wrong}» بنستعملها مع ${male ? 'المؤنث' : 'المذكر'}، و«${n}» ${male ? 'مذكر' : 'مؤنث'}.`],
    ['هل', 'هل أداة استفهام، وليست مما يُتوصل به إلى نداء ما فيه (ال).'],
  ], 2)
}

